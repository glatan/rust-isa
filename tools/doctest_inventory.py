#!/usr/bin/env python3
"""Generate per-extension doctest inventories.

Every public instruction is imported in the rustdoc example of its extension
module. The import is compiled by rustdoc, so a renamed or removed wrapper
breaks the doctest. Instruction behavior is covered by the value tests; these
examples keep every public path in the doctest layer.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from doc_names import SKIP_ROWS, normalize_extension, table_rows
from mnemonics import ROOT, macro_line_ranges

SOURCE = ROOT / "src"
START = "//! <!-- doctest-inventory:start -->"
END = "//! <!-- doctest-inventory:end -->"
PUBLIC_MOD = re.compile(r"^\s*(?:#\[[^\]]+\]\s*)?pub\s+mod\s+([A-Za-z_][A-Za-z0-9_]*)\s*;", re.M)
REEXPORT_LIST = re.compile(r"pub use [^;]*?::\{([^}]*)\};", re.S)
REEXPORT_SINGLE = re.compile(
    r"pub use [^;]*?::([A-Za-z_][A-Za-z0-9_]*)(?:\s+as\s+([A-Za-z_][A-Za-z0-9_]*))?;",
    re.S,
)

# Stateful extension APIs that are associated functions rather than free
# functions. Each entry is (type, function) and is listed in the arch README.
EXTRA = {
    "aarch64/simd/sme": [("SmeGuard", "enter")],
    "powerpc/matrix/mma": [("MmaAccumulator", "new")],
    "x86/matrix/amx_tile": [
        ("AmxGuard", "enter"),
        ("TileConfig", "builder"),
        ("TileConfig", "from_bytes"),
    ],
}


def public_leaves(arch: str) -> list[Path]:
    """Return public leaf module directories for an architecture."""
    root = SOURCE / arch
    leaves: list[Path] = []

    def walk(directory: Path) -> None:
        mod = directory / "mod.rs"
        if not mod.is_file():
            return
        text = mod.read_text(encoding="utf-8")
        children = [
            directory / name
            for name in PUBLIC_MOD.findall(text)
            if (directory / name / "mod.rs").is_file()
        ]
        if not children:
            leaves.append(directory)
            return
        for child in children:
            walk(child)

    walk(root)
    return leaves


def cfg_attributes(lines: list[str], index: int) -> set[str]:
    found: set[str] = set()
    index -= 1
    while index >= 0:
        line = lines[index].strip()
        if not line or line.startswith(("///", "//")):
            index -= 1
            continue
        if line.startswith("#["):
            if line.startswith("#[cfg("):
                found.add(line)
            index -= 1
            continue
        break
    return found


def instruction_entries(directory: Path) -> list[tuple[str, tuple[str, ...]]]:
    entries: dict[str, set[str]] = {}
    for path in sorted(directory.rglob("*.rs")):
        text = path.read_text(encoding="utf-8")
        lines = text.splitlines()
        for index, line in enumerate(lines):
            match = re.match(r"^pub\s+(?:unsafe\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)", line)
            if match:
                entries.setdefault(match.group(1), set()).update(
                    cfg_attributes(lines, index)
                )
        # Wrappers generated by macros carry their identifiers as the first
        # non-doc, non-attribute arguments. The segment macro generates four
        # functions from one invocation.
        for start, end in macro_line_ranges(text):
            limit = min(end, len(lines) - 1)
            header = lines[start]
            macro_name = header.split("!(", 1)[0].strip()
            want = 4 if macro_name == "segment" else 1
            if macro_name == "vfcmp_conditions":
                want = 1_000_000
            found: list[str] = []
            index = start
            while index <= limit and len(found) < want:
                line = lines[index]
                if not line.strip() or line.lstrip().startswith(
                    ("///", "//", "#[")
                ):
                    index += 1
                    continue
                if "!(" in line:
                    line = line.split("!(", 1)[1]
                    if not line.strip():
                        index += 1
                        continue
                # vfcmp_conditions! passes (name_s, name_d, condition).
                if line.lstrip().startswith("("):
                    names = re.findall(r"([A-Za-z_][A-Za-z0-9_]*)\s*,", line)
                    for name in names:
                        entries.setdefault(name, set()).update(
                            cfg_attributes(lines, start)
                        )
                        found.append(name)
                    index += 1
                    continue
                match = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*,", line)
                if match:
                    name = match.group(1)
                    entries.setdefault(name, set()).update(
                        cfg_attributes(lines, start)
                    )
                    found.append(name)
                index += 1
        for match in REEXPORT_LIST.finditer(text):
            line_number = text.count("\n", 0, match.start())
            cfgs = cfg_attributes(lines, line_number)
            for item in match.group(1).split(","):
                item = item.strip()
                if not item or "*" in item:
                    continue
                name = item.split(" as ")[-1].strip()
                if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                    entries.setdefault(name, set()).update(cfgs)
        for match in REEXPORT_SINGLE.finditer(text):
            name = match.group(2) or match.group(1)
            if name == "*":
                continue
            line_number = text.count("\n", 0, match.start())
            entries.setdefault(name, set()).update(cfg_attributes(lines, line_number))
    return [
        (name, tuple(sorted(cfgs)))
        for name, cfgs in sorted(entries.items())
    ]


def block(directory: Path) -> str:
    entries = instruction_entries(directory)
    if not entries:
        return ""
    module = "rust_isa::" + "::".join(directory.relative_to(SOURCE).parts)
    lines = [
        START,
        "//!",
        "//! # Instruction inventory",
        "//!",
        "//! ```",
    ]
    for name, cfgs in entries:
        lines.extend(f"//! {cfg}" for cfg in cfgs)
        lines.append(f"//! use {module}::{name} as _;")
    extra = EXTRA.get(directory.relative_to(SOURCE).as_posix(), [])
    for type_name in sorted({type_name for type_name, _ in extra}):
        lines.append(f"//! use {module}::{type_name};")
    for type_name, function in extra:
        lines.append(f"//! let _ = {type_name}::{function};")
    lines.extend(["//! ```", END])
    return "\n".join(lines)


def insert_block(text: str, inventory: str) -> str:
    start = text.find(START)
    if start >= 0:
        end = text.find(END, start)
        if end < 0:
            raise SystemExit(f"missing {END}")
        end += len(END)
        return (text[:start] + inventory + text[end:]).rstrip() + "\n"

    lines = text.splitlines()
    index = 0
    while index < len(lines) and (
        not lines[index].strip() or lines[index].lstrip().startswith("//!")
    ):
        index += 1
    prefix = "\n".join(lines[:index]).rstrip()
    suffix = "\n".join(lines[index:]).lstrip("\n")
    if prefix:
        return (prefix + "\n\n" + inventory + "\n\n" + suffix).rstrip() + "\n"
    return (inventory + "\n\n" + suffix).rstrip() + "\n"


def inventory_blocks() -> dict[tuple[str, str], str]:
    found: dict[tuple[str, str], str] = {}
    for path in SOURCE.rglob("mod.rs"):
        text = path.read_text(encoding="utf-8")
        start = text.find(START)
        if start < 0:
            continue
        end = text.find(END, start)
        if end < 0:
            continue
        relative = path.parent.relative_to(SOURCE)
        found[(relative.parts[0], relative.name)] = text[start:end]
    return found


def inventory_names(text: str) -> set[str]:
    names = set(
        re.findall(r"use rust_isa::[^;]*::([A-Za-z_][A-Za-z0-9_]*) as _;", text)
    )
    names.update(re.findall(r"let _ = [A-Za-z_][A-Za-z0-9_]*::([A-Za-z_][A-Za-z0-9_]*);", text))
    return names


def missing_documented() -> list[tuple[str, str, str]]:
    blocks = inventory_blocks()
    missing = []
    for arch, extension, names in table_rows():
        key = normalize_extension(extension)
        if "/" in extension or (arch, key) in SKIP_ROWS:
            continue
        texts = [
            text
            for (block_arch, block_name), text in blocks.items()
            if block_arch == arch and block_name == key
        ]
        if not texts:
            # A re-export alias without its own module directory. The
            # canonical extension row is checked separately.
            continue
        covered = set()
        for text in texts:
            covered.update(inventory_names(text))
        for name in names:
            if name not in covered:
                missing.append((arch, extension, name))
    return missing


def remove_block(text: str) -> str:
    start = text.find(START)
    if start < 0:
        return text
    end = text.find(END, start)
    if end < 0:
        return text
    end += len(END)
    before = text[:start].rstrip()
    after = text[end:].lstrip("\n")
    if before and after:
        return before + "\n\n" + after
    return before + after


def changed_files() -> list[tuple[Path, str, str]]:
    changes: list[tuple[Path, str, str]] = []
    for arch in sorted(path.name for path in SOURCE.iterdir() if path.is_dir()):
        for directory in public_leaves(arch):
            inventory = block(directory)
            path = directory / "mod.rs"
            old = path.read_text(encoding="utf-8")
            new = insert_block(old, inventory) if inventory else remove_block(old)
            if new != old:
                changes.append((path, old, new))
    return changes


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write the inventories")
    parser.add_argument("--check", action="store_true", help="fail if an inventory is stale")
    args = parser.parse_args()

    changes = changed_files()
    if args.write:
        for path, _, new in changes:
            path.write_text(new, encoding="utf-8")
        print(f"updated {len(changes)} module doctests")
        return
    if args.check:
        for path, _, _ in changes:
            print(f"stale doctest inventory: {path.relative_to(ROOT)}")
        missing = missing_documented()
        for arch, extension, name in missing:
            print(f"missing inventory entry: {arch} {extension} {name}")
        if changes or missing:
            raise SystemExit(1)
        print("doctest inventories: ok")
        return
    for path, _, _ in changes:
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
