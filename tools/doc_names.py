#!/usr/bin/env python3
"""Check that public instruction wrappers appear in the arch docs tables.

The docs tables are the source of truth for the public inventory. This
script compares the names in each extension row with the top-level public
functions and the documented macro-generated wrappers in the matching
source directory. Rows that only record a count (for example ``236 命令``)
are skipped because they do not list names.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from mnemonics import ROOT, macro_line_ranges

DOCS = ROOT / "docs"
SOURCE = ROOT / "src"

NUMBERED = re.compile(r"^\d+\s*命令")
PUBLIC_FN = re.compile(
    r"^pub(?:\([^)]*\))?\s+(?:unsafe\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)"
)
MACRO_ARG = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*,")

# Rows whose names are a subset of another extension or a feature alias.
# The source-to-row mapping is not one-to-one, so they are not checked.
SKIP_ROWS = {
    ("mips", "fp64"),
    ("riscv", "unaligned_vector_mem"),
    # Zbkc is the crypto subset of Zbc. The wrappers live in zbc.
    ("riscv", "zbkc"),
}

# Families whose lane/suffix variants are intentionally represented by one
# row name. The key is (arch, extension), the value is a prefix list.
FAMILY_PREFIXES = {
    ("loongarch", "lsx"): [
        "vavgr",
        "vexth",
        "vextl",
        "vfadd",
        "vfsub",
        "vfmul",
        "vfdiv",
        "vfmax",
        "vfmin",
        "vffint",
        "vftint",
        "vssr",
        "vsat",
        "vfcmp",
        "vrepl",
    ],
    ("loongarch", "lasx"): [
        "xvavgr",
        "xvfadd",
        "xvfsub",
        "xvfmul",
        "xvfdiv",
        "xvfmax",
        "xvfcmp",
        "xvffint",
        "xvftint",
        "xvssr",
        "xvsat",
        "xvrepl",
    ],
}


def normalize_extension(extension: str) -> str:
    extension = extension.replace("系", "").strip()
    extension = extension.split()[0] if extension else extension
    return extension.replace("-", "_").replace(".", "_")


def table_rows():
    for readme in sorted(DOCS.glob("*/README.md")):
        arch = readme.parent.name
        for raw in readme.read_text(encoding="utf-8").splitlines():
            if not raw.startswith("|"):
                continue
            cells = [cell.strip() for cell in raw.strip().strip("|").split("|")]
            if len(cells) < 4 or not cells[0].startswith("`"):
                continue
            extension = cells[0].replace("`", "").strip()
            if NUMBERED.match(cells[1].strip()):
                continue
            names = set(re.findall(r"`([^`]+)`", cells[1]))
            if names:
                yield arch, extension, names


def source_names(arch: str, extension: str):
    directory = normalize_extension(extension)
    directories = [
        path
        for path in (SOURCE / arch).rglob("*")
        if path.is_dir() and path.name == directory
    ]
    if not directories:
        return None

    names: set[str] = set()
    for directory_path in directories:
        for path in directory_path.rglob("*.rs"):
            text = path.read_text(encoding="utf-8")
            lines = text.splitlines()
            for line in lines:
                match = PUBLIC_FN.match(line)
                if match:
                    names.add(match.group(1))

            # Wrappers are often generated by a macro invocation with a
            # rustdoc argument: ``binary!(/// `vadd`. add, rust_isa...);``.
            for start, end in macro_line_ranges(text):
                limit = min(end, len(lines) - 1)
                i = start
                while i <= limit:
                    if not lines[i].lstrip().startswith("///"):
                        i += 1
                        continue
                    while i <= limit and lines[i].lstrip().startswith("///"):
                        i += 1
                    while i <= limit and (
                        not lines[i].strip() or lines[i].lstrip().startswith("#[")
                    ):
                        i += 1
                    if i <= limit:
                        match = MACRO_ARG.match(lines[i])
                        if match:
                            names.add(match.group(1))
                    i += 1
    return names


MACRO_FIRST_ARG = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*,")
ALL_EXTENSIONS: set[str] = set()


def macro_first_arguments(arch: str, extension: str):
    directory = normalize_extension(extension)
    directories = [
        path
        for path in (SOURCE / arch).rglob("*")
        if path.is_dir() and path.name == directory
    ]
    names: set[str] = set()
    for directory_path in directories:
        for path in directory_path.rglob("*.rs"):
            text = path.read_text(encoding="utf-8")
            lines = text.splitlines()
            for start, end in macro_line_ranges(text):
                limit = min(end, len(lines) - 1)
                for index in range(start, limit + 1):
                    line = lines[index]
                    if not line.strip() or line.lstrip().startswith(("///", "//", "#[")):
                        continue
                    match = MACRO_FIRST_ARG.match(line)
                    if match:
                        names.add(match.group(1))
                    break
    return names


REEXPORT_LIST = re.compile(r"pub use\s+[^;]*?::\{([^}]*)\};")
REEXPORT_SINGLE = re.compile(r"pub use\s+[^;]*?::([A-Za-z_][A-Za-z0-9_]*)(?:\s+as\s+([A-Za-z_][A-Za-z0-9_]*))?;")


def reexport_names(text: str) -> set[str]:
    names: set[str] = set()
    for match in REEXPORT_LIST.finditer(text):
        for item in match.group(1).split(","):
            item = item.strip()
            if not item:
                continue
            item = item.split(" as ")[-1].strip()
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", item):
                names.add(item)
    for match in REEXPORT_SINGLE.finditer(text):
        names.add(match.group(2) or match.group(1))
    return names


def arch_names(arch: str) -> set[str]:
    names: set[str] = set()
    for path in (SOURCE / arch).rglob("*.rs"):
        text = path.read_text(encoding="utf-8")
        lines = text.splitlines()
        for line in lines:
            match = re.match(
                r"^\s*pub(?:\([^)]*\))?\s+(?:unsafe\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)",
                line,
            )
            if match:
                names.add(match.group(1))
        names.update(reexport_names(text))
        for start, end in macro_line_ranges(text):
            limit = min(end, len(lines) - 1)
            macro_name = ""
            header = re.search(r"([A-Za-z_][A-Za-z0-9_]*)!\s*[\[({]", lines[start])
            if header:
                macro_name = header.group(1)
            want = 4 if macro_name == "segment" else 1
            found = 0
            for index in range(start, limit + 1):
                line = lines[index]
                if not line.strip() or line.lstrip().startswith(("///", "//", "#[")):
                    continue
                if "!(" in line and found == 0:
                    tail = line.rsplit("!(", 1)[1]
                    match = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)\s*,", tail)
                    if match:
                        names.add(match.group(1))
                        found += 1
                    continue
                match = MACRO_FIRST_ARG.match(line)
                if match:
                    names.add(match.group(1))
                    found += 1
                    if found >= want:
                        break
                elif found:
                    break
    return names


def covered_by_family(arch: str, extension: str, name: str) -> bool:
    for prefix in FAMILY_PREFIXES.get((arch, normalize_extension(extension)), []):
        if name.startswith(prefix):
            return True
    return False


def check() -> list[str]:
    problems: list[str] = []
    global ALL_EXTENSIONS
    ALL_EXTENSIONS = {
        normalize_extension(extension)
        for _, extension, _ in table_rows()
    } | {extension for _, extension, _ in table_rows()}
    seen_rows: set[tuple[str, str]] = set()
    for arch, extension, documented in table_rows():
        key = (arch, normalize_extension(extension))
        if key in seen_rows:
            continue
        seen_rows.add(key)
        if "/" in extension or key in SKIP_ROWS:
            continue
        source = source_names(arch, extension)
        if source is None:
            problems.append(f"{arch}: no source directory for `{extension}`")
            continue
        missing = sorted(
            name
            for name in source - documented
            if not covered_by_family(arch, extension, name)
        )
        if missing:
            problems.append(
                f"{arch}/{extension}: missing from docs table: " + ", ".join(missing)
            )
        known = arch_names(arch)
        extra = sorted(
            name
            for name in documented - known
            if "-" not in name and name not in ALL_EXTENSIONS
        )
        if extra:
            problems.append(
                f"{arch}/{extension}: docs name has no source wrapper: "
                + ", ".join(extra)
            )
    return problems


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate the source-to-docs inventory and exit nonzero on errors",
    )
    args = parser.parse_args()
    if args.check:
        problems = check()
        if problems:
            for problem in problems:
                print(problem)
            raise SystemExit(1)
        print("doc names: ok")
        return
    for problem in check():
        print(problem)


if __name__ == "__main__":
    main()
